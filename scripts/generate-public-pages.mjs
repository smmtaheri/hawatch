#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const checkOnly = process.argv.includes("--check");
const manifestPath = path.join(root, "apps/api/src/hawatch/config/public_pages.json");
const manifest = JSON.parse(await readFile(manifestPath, "utf8"));

if (manifest.version !== 1 || !Array.isArray(manifest.pages) || !Array.isArray(manifest.redirects)) {
  throw new Error("Unsupported or malformed public page manifest.");
}

const converters = {
  slug: { django: "slug", nginx: "[-A-Za-z0-9_]+" },
  int: { django: "int", nginx: "[0-9]+" },
  str: { django: "str", nginx: "[^/]+" },
};
const componentNames = new Set();
const routeIds = new Set();
const djangoNames = new Set();
const canonicalPaths = new Set();

function assertUnique(set, value, kind) {
  if (set.has(value)) throw new Error(`Duplicate ${kind}: ${value}`);
  set.add(value);
}

function parametersIn(route) {
  const found = [...route.matchAll(/\{([a-z][a-z0-9_-]*):([a-z]+)\}/g)];
  const residue = route.replace(/\{([a-z][a-z0-9_-]*):([a-z]+)\}/g, "");
  if (/[{}]/.test(residue)) throw new Error(`Malformed parameter in route: ${route}`);
  return found;
}

function validatePage(page) {
  assertUnique(routeIds, page.id, "public page id");
  assertUnique(canonicalPaths, page.path, "public page path");
  if (!page.path.startsWith("/") || page.path.length > 1 && page.path.endsWith("/")) {
    throw new Error(`Page paths must be absolute and canonical without a trailing slash: ${page.path}`);
  }
  if (!page.component || !/^[a-z][a-z0-9-]*$/.test(page.component)) {
    throw new Error(`Invalid React component key for ${page.id}.`);
  }
  componentNames.add(page.component);
  const params = parametersIn(page.path);
  const paramNames = new Set();
  for (const [, name, type] of params) {
    if (!converters[type]) throw new Error(`Unsupported route converter ${type} in ${page.path}`);
    assertUnique(paramNames, name, `parameter in ${page.path}`);
  }
  if (page.owner === "api") {
    if (!page.view || !page.name) throw new Error(`API page ${page.id} needs a Django view and route name.`);
    assertUnique(djangoNames, page.name, "Django route name");
  } else if (page.owner !== "web" || page.view || page.name || !/^[a-z][a-z0-9-]*\.html$/.test(page.shell ?? "")) {
    throw new Error(`Web page ${page.id} must declare an HTML shell and no Django view or route name.`);
  }
}

for (const page of manifest.pages) validatePage(page);
for (const redirect of manifest.redirects) {
  assertUnique(routeIds, redirect.id, "public page id");
  assertUnique(canonicalPaths, redirect.path, "public page path");
  if (redirect.owner !== "api" || !redirect.path.startsWith("/") || redirect.path.length > 1 && redirect.path.endsWith("/") || !redirect.view || !redirect.name || !redirect.target || parametersIn(redirect.path).length) {
    throw new Error(`Malformed public redirect ${redirect.id}.`);
  }
  assertUnique(djangoNames, redirect.name, "Django route name");
}

function djangoPath(route) {
  return route.replace(/\{([a-z][a-z0-9_-]*):([a-z]+)\}/g, (_, name, type) => `<${converters[type].django}:${name}>`);
}

function reactPath(route) {
  return route.replace(/\{([a-z][a-z0-9_-]*):[a-z]+\}/g, ":$1");
}

function nginxPath(route) {
  return route.split(/(\{[a-z][a-z0-9_-]*:[a-z]+\})/g).map((part) => {
    const parameter = part.match(/^\{[a-z][a-z0-9_-]*:([a-z]+)\}$/);
    if (parameter) return converters[parameter[1]].nginx;
    return part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  }).join("");
}

function nginxLocationPattern() {
  const alternatives = manifest.pages
    .filter((page) => page.owner === "api" && page.path !== "/")
    .map((page) => nginxPath(page.path).replace(/^\//, ""))
    .sort((left, right) => right.length - left.length);
  return `^/(?:${alternatives.join("|")})/?$`;
}

function generatedTs() {
  const routes = manifest.pages.flatMap((page) => {
    const base = reactPath(page.path);
    const paths = page.trailing_slash && base !== "/" ? [base, `${base}/`] : [base];
    return paths.map((routePath) => ({ id: page.id, path: routePath, component: page.component }));
  });
  const components = [...componentNames].sort().map((name) => JSON.stringify(name)).join(" | ");
  return `// Generated by scripts/generate-public-pages.mjs from public_pages.json. Do not edit.\nexport type PublicPageComponent = ${components};\n\nexport const PUBLIC_PAGE_ROUTES = ${JSON.stringify(routes, null, 2)} as const satisfies readonly { id: string; path: string; component: PublicPageComponent }[];\n`;
}

function proxyLocation(upstream) {
  const settings = `    proxy_pass ${upstream};\n    proxy_http_version 1.1;\n    proxy_set_header Host $host;\n    proxy_set_header X-Real-IP $remote_addr;\n    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;\n    proxy_set_header X-Forwarded-Proto $hawatch_forwarded_proto;\n    proxy_connect_timeout 3s;\n    proxy_read_timeout 30s;\n    proxy_send_timeout 30s;\n    proxy_next_upstream error timeout http_502 http_503 http_504;`;
  return `location = / {\n${settings}\n}\n\nlocation ~ ${nginxLocationPattern()} {\n${settings}\n}`;
}

function redirectLocations(target = "manifest") {
  const redirects = manifest.redirects.flatMap((redirect) => {
    const locations = redirect.trailing_slash && redirect.path !== "/" ? [redirect.path, `${redirect.path}/`] : [redirect.path];
    return locations.map((location) => `location = ${location} { return 301 ${target === "manifest" ? redirect.target : target}; }`);
  });
  return redirects;
}

function webShellLocations({ qa = false } = {}) {
  return manifest.pages.filter((page) => page.owner === "web").flatMap((page) => {
    const locations = page.trailing_slash && page.path !== "/" ? [page.path, `${page.path}/`] : [page.path];
    return locations.map((location) => {
      const cache = !qa && page.cache_control ? `\n    add_header Cache-Control "${page.cache_control}" always;` : "";
      return `location = ${location} {${cache}\n    try_files /${page.shell} =404;\n}`;
    });
  });
}

function generatedWebNginx(upstream, { includeShells = false } = {}) {
  const blocks = [...redirectLocations(), proxyLocation(upstream)];
  if (includeShells) blocks.push(...webShellLocations());
  return `# Generated by scripts/generate-public-pages.mjs from public_pages.json. Do not edit.\n${blocks.join("\n\n")}\n`;
}

function generatedQaNginx() {
  return `# Generated by scripts/generate-public-pages.mjs from public_pages.json. Do not edit.\n${webShellLocations({ qa: true }).join("\n\n")}\n`;
}

function generatedStageNginx() {
  return `# Generated by scripts/generate-public-pages.mjs from public_pages.json. Do not edit.\n${[...redirectLocations("/"), "location = / { proxy_pass $stage_api; }", `location ~ ${nginxLocationPattern()} { proxy_pass $stage_api; }`].join("\n\n")}\n`;
}

const outputs = new Map([
  ["apps/web/src/app/publicPageRoutes.generated.ts", generatedTs()],
  ["apps/web/nginx-public-pages.inc", generatedWebNginx("http://hawatch_api", { includeShells: true })],
  ["apps/web/nginx-qa-public-pages.inc", generatedQaNginx()],
  ["infra/nginx/public-pages.inc", generatedWebNginx("http://hawatch_api")],
  ["infra/nginx/stage-public-pages.inc", generatedStageNginx()],
]);

for (const [relativePath, expected] of outputs) {
  const absolutePath = path.join(root, relativePath);
  let actual = "";
  try {
    actual = await readFile(absolutePath, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (checkOnly) {
    if (actual !== expected) throw new Error(`${relativePath} is stale. Run node scripts/generate-public-pages.mjs.`);
  } else if (actual !== expected) {
    await writeFile(absolutePath, expected, "utf8");
    process.stdout.write(`generated ${relativePath}\n`);
  }
}
